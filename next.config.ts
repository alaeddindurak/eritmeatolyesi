import type { NextConfig } from "next";

/**
 * The site is published at https://alaeddindurak.github.io/eritmeatolyesi/ (a sub-path),
 * so the production build needs this prefix. In development it stays empty so the site
 * opens at http://localhost:3000. Remove the prefix if a custom domain is connected later.
 */
const basePath = process.env.NODE_ENV === "production" ? "/eritmeatolyesi" : "";

const nextConfig: NextConfig = {
  // Export the site as plain static files (HTML/CSS/JS) so it can be hosted on GitHub Pages.
  output: "export",
  // Produces /gallery/index.html instead of /gallery.html, which static hosts serve reliably.
  trailingSlash: true,
  // The default image optimizer needs a server, so it is disabled for static export.
  images: { unoptimized: true },
  basePath: basePath || undefined,
  // Makes the prefix available to client code (see src/lib/base-path.ts).
  env: { NEXT_PUBLIC_BASE_PATH: basePath },
  // Route Tailwind CSS through its Turbopack loader (generated by create-next-app).
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
